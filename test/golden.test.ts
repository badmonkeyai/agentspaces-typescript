test("subordinate agent certificate and agent-signed record match Java (SPEC 4.2, 11a.3)", () => {
  // QA4 A4-7 phase 1: the peer certifies an agent key; the agent key signs
  // the record; the DTO carries both.
  const id = identity();
  const issued = GOLDEN["certificate_verify_at"];
  const agent = id.subordinate("python", issued, "PT24H",
    Identity.fromPkcs8(hex("agent_private_key_pkcs8")));
  assert.equal(agent.agentId, id.agent("python"));
  assert.deepEqual(Buffer.from(agent.publicRaw), hex("agent_public_key_raw"));
  assert.deepEqual(dumps(certificateBody(agent.certificate)), hex("agent_certificate_unsigned_cbor"));
  assert.deepEqual(Buffer.from(agent.certificate["peerSignature"] as Uint8Array),
    hex("agent_certificate_signature"));
  assert.deepEqual(dumps(agent.certificate), hex("agent_certificate_cbor"));
  const nowMillis = parseInstantMillis(issued);
  assert.equal(verifyAgentCertificate(loads(hex("agent_certificate_cbor")), id.publicRaw,
    id.agent("python"), nowMillis), true);
  // Expiry is inclusive: issued + ttl is the first refused instant.
  assert.equal(verifyAgentCertificate(agent.certificate, id.publicRaw, id.agent("python"),
    nowMillis + parseDurationMillis("PT24H") - 1), true);
  assert.equal(verifyAgentCertificate(agent.certificate, id.publicRaw, id.agent("python"),
    nowMillis + parseDurationMillis("PT24H")), false);

  const view = hex("sign_view_cbor");
  const sig = agent.sign(view);
  assert.deepEqual(Buffer.from(sig), hex("record_signature_agent_key"));
  assert.equal(Identity.verify(agent.publicRaw, view, sig), true);
  assert.equal(Identity.verify(id.publicRaw, view, sig), false); // not the peer's

  const leaseValue = { holder: id.agent("python"), expiresAtMillis: 1735693200000, kind: "WRITE" };
  const record: Dict = {
    entryId: "11111111-2222-3333-4444-555555555555", spaceId: GOLDEN["space_id"],
    type: "GoldenVectors$ResearchTask#v1", payload: hex("task_payload_cbor"),
    payloadRef: null, issuer: id.agent("python"), issued: GOLDEN["hlc_encoded"],
    lease: leaseValue, tags: {}, sig,
  };
  const dto: Dict = {
    record, issuerPublicKey: id.publicRaw,
    adds: [{ replica: id.peerId, counter: 1 }], removes: [],
    leaseStamp: GOLDEN["hlc_encoded"], leaseValue, completed: false,
    stateSig: hex("state_signature"), agentCertificate: agent.certificate,
  };
  assert.deepEqual(dumps(dto), hex("entry_state_with_certificate_cbor"));
  assert.deepEqual(dumps({ state: dto, claimEntry: null, claim: null }),
    hex("delta_with_certificate_cbor"));
  assert.equal(wire.verifyRecord(record, id.publicRaw, agent.certificate, nowMillis), true);

  // SPEC §11a.4 v0.1.13 (A6): that state is peer-signed on an agent-attested
  // entry and is refused; the agent-signed state is what lands.
  const peer = new Peer(id, GOLDEN["group_id"], () => nowMillis);
  const fold = (name: string) => (peer as unknown as { fold(dto: Dict): void })
    .fold((loads(hex(name)) as Dict)["state"] as Dict);
  fold("delta_with_certificate_cbor");
  assert.equal(peer.states.size, 0);
  const signer = id.agent("python");
  const signedAt = GOLDEN["hlc_encoded"];
  const stateView = wire.stateSignView(GOLDEN["space_id"], String(record["entryId"]),
    dto["adds"] as Dict[], [], signedAt, leaseValue, false, signer, signedAt);
  assert.deepEqual(dumps(stateView), hex("state_sign_view_agent_cbor"));
  const agentStateSig = agent.sign(dumps(stateView));
  assert.deepEqual(Buffer.from(agentStateSig), hex("state_signature_agent_key"));
  const agentDto: Dict = { record, issuerPublicKey: id.publicRaw, adds: dto["adds"], removes: [],
    leaseStamp: signedAt, leaseValue, completed: false, stateSig: agentStateSig,
    agentCertificate: agent.certificate, stateCertificate: agent.certificate, signer, signedAt };
  assert.deepEqual(dumps(agentDto), hex("entry_state_agent_signed_cbor"));
  assert.deepEqual(dumps({ state: agentDto, claimEntry: null, claim: null }),
    hex("delta_agent_signed_cbor"));
  fold("delta_agent_signed_cbor");
  fold("delta_cbor");
  assert.deepEqual([...peer.states.keys()], ["11111111-2222-3333-4444-555555555555"]);
});

