const FOUNDING = {
  name: "golden-fleet", policy: "OPEN", strategy: "LEASE_RACE", fanout: 3,
  period: "PT1S", issued: "2026-01-01T00:00:00Z", ttl: "PT24H",
};

function golden(): Dict {
  return foundGroup(identity(), FOUNDING.name, FOUNDING.policy, FOUNDING.strategy,
    FOUNDING.fanout, FOUNDING.period, FOUNDING.issued, FOUNDING.ttl);
}

test("group founding derives the self-certifying GroupID like Java (SPEC 4.4, 5.1)", () => {
  const id = identity();
  const fields = foundingFields(FOUNDING.name, id.peerId, FOUNDING.issued,
    FOUNDING.ttl, FOUNDING.policy, FOUNDING.strategy, FOUNDING.fanout, FOUNDING.period);
  assert.deepEqual(dumps(fields), hex("founding_fields_cbor"));
  const signature = id.sign(dumps(fields));
  assert.deepEqual(Buffer.from(signature), hex("founding_signature"));
  const document = dumps(foundingDocument(fields, signature));
  assert.deepEqual(document, hex("founding_document_cbor"));
  assert.equal(groupIdFromFoundingDocument(document), GOLDEN["founding_group_id"]);

  const signed = golden();
  const ad = signed["advertisement"] as Dict;
  assert.equal(ad["group"], GOLDEN["founding_group_id"]);
  assert.equal(ad["id"], GOLDEN["founding_ad_id"]);
  assert.deepEqual(dumps(ad), hex("group_ad_cbor"));
  assert.deepEqual(dumps(signed), hex("signed_group_ad_cbor"));
  assert.deepEqual(dumps(foundingFieldsOf(ad)), hex("founding_fields_cbor"));

  // The four checks pass on the genuine document, from the Dict and from bytes.
  assert.equal(verifySignedGroupAd(signed), GOLDEN["founding_group_id"]);
  assert.equal(verifySignedGroupAd(hex("signed_group_ad_cbor")), GOLDEN["founding_group_id"]);
});

test("adversarial GROUP_AD answers fail the four checks (SPEC 5.1)", () => {
  // A genuine founder signature under the wrong GroupID: the founding
  // document still derives to the real group, which is exactly why the
  // advertised group is refused.
  const wrongId = loads(hex("adv_group_ad_wrong_id_cbor")) as Dict;
  assert.equal(verifySignedGroupAd(wrongId), null);
  const wrongAd = wrongId["advertisement"] as Dict;
  assert.equal(wrongAd["group"], GOLDEN["group_id"]);
  assert.equal(groupIdFromFoundingDocument(dumps(foundingDocument(
    foundingFieldsOf(wrongAd), wrongId["signature"] as Uint8Array))),
    GOLDEN["founding_group_id"]);

  // The right group and the golden founder key, signed by someone else.
  const forged = loads(hex("adv_group_ad_forged_signature_cbor")) as Dict;
  assert.equal(verifySignedGroupAd(forged), null);
  assert.equal((forged["advertisement"] as Dict)["group"], GOLDEN["founding_group_id"]);
  const forger = Identity.fromPkcs8(hex("adv_forger_private_key_pkcs8"));
  assert.ok(Identity.verify(forger.publicRaw, hex("founding_fields_cbor"),
    forged["signature"] as Uint8Array), "the forged vector is signed by the forger key");

  // Malformed inputs are refused, never thrown.
  assert.equal(verifySignedGroupAd(null), null);
  assert.equal(verifySignedGroupAd(Buffer.from([0xff])), null);
  assert.equal(verifySignedGroupAd({ advertisement: {}, founderPublicKey: new Uint8Array(32),
    signature: new Uint8Array(64) }), null);
});

